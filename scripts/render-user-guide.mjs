import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
await mkdir('output/pdf', { recursive: true });
await mkdir('artifacts/manual-qa', { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1060 }, deviceScaleFactor: 1 });
const errors=[]; page.on('pageerror', e=>errors.push(e.message));
const file=pathToFileURL(path.resolve('docs/USER-GUIDE.html')).href;
await page.goto(file); await page.evaluate(()=>document.fonts.ready);
const check=async label=>{
  const overflow=await page.evaluate(()=>({page:document.documentElement.scrollWidth>innerWidth, elements:[...document.querySelectorAll('main *')].filter(e=>e.getBoundingClientRect().right>innerWidth+1).map(e=>e.tagName)}));
  if(overflow.page||overflow.elements.length)throw Error(`${label} overflow: ${JSON.stringify(overflow)}`);
};
await check('wide');
await page.screenshot({path:'artifacts/manual-qa/guide-wide.png'});
await page.getByRole('button',{name:'어두운 화면',exact:true}).click();
if(await page.locator('#theme').getAttribute('aria-pressed')!=='true')throw Error('Theme control failed');
await page.screenshot({path:'artifacts/manual-qa/guide-dark.png'});
await page.getByRole('button',{name:'밝은 화면',exact:true}).click();
await page.locator('nav a[href="#connect"]').click();
await page.getByRole('button',{name:'주소 복사',exact:true}).click();
await page.waitForFunction(()=>document.querySelector('#feedback').textContent.length>0);
const copyStatus=await page.locator('#feedback').textContent();
await page.evaluate(()=>{window.print=()=>{document.body.dataset.printCalled='yes';};});
await page.getByRole('button',{name:'인쇄 / PDF',exact:true}).click();
if(await page.locator('body').getAttribute('data-print-called')!=='yes')throw Error('Print control failed');
await page.setViewportSize({width:390,height:844});
await page.goto(file); await check('narrow');
await page.screenshot({path:'artifacts/manual-qa/guide-mobile-top.png'});
await page.screenshot({path:'artifacts/manual-qa/guide-mobile.png',fullPage:true});
await page.setViewportSize({width:1440,height:1060});
await page.pdf({path:'output/pdf/Translate-AI-사용설명서.pdf',preferCSSPageSize:true,printBackground:true,displayHeaderFooter:true,headerTemplate:'<span></span>',footerTemplate:'<div style="width:100%;font-family:Arial,sans-serif;font-size:8px;color:#53675e;text-align:center">Translate AI · 2026-10-24 &nbsp; | &nbsp; <span class="pageNumber"></span> / <span class="totalPages"></span></div>'});
if(errors.length)throw Error(errors.join('\n'));
await writeFile('artifacts/manual-qa/results.json',JSON.stringify({wide:1440,narrow:390,noHorizontalOverflow:true,theme:true,print:true,copyStatus,consoleErrors:errors,pdf:'output/pdf/Translate-AI-사용설명서.pdf'},null,2));
await browser.close(); console.log('Manual wide/narrow, theme, copy feedback and print checks passed.');
